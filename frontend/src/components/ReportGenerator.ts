// Report Generator Utility - Exports Executive Security & Self-Healing Audit Reports

export function generateAuditReport(incidents: any[], targetUrl: string, totalScans: number) {
  const timestamp = new Date().toISOString();
  const dateFormatted = new Date().toLocaleDateString();
  const healedCount = incidents.filter(i => i.status === "PATCHED" || i.status === "HEALING" || i.status === "PR_CREATED").length;
  const healthScore = incidents.length === 0 ? 100 : Math.max(20, Math.round((healedCount / incidents.length) * 100));

  let md = `# 🛡️ Ghost-QA Sentinel — Executive Autonomous Quality & Security Report

**Target URL:** \`${targetUrl}\`  
**Audit Timestamp:** \`${timestamp}\`  
**Overall System Health Score:** \`${healthScore}% (A+ Grade)\`  
**Generated by:** Ghost-QA Autonomous Chaos Crawler & Google Gemini AI Engine

---

## 📊 Executive Summary

- **Total Chaos Scans Executed:** ${totalScans}
- **Defects & Runtime Incidents Intercepted:** ${incidents.length}
- **Autonomous AI Resolutions (Self-Healed):** ${healedCount} (${healthScore}%)
- **Active Git Pull Requests Dispatched:** ${incidents.filter(i => i.status === "PR_CREATED").length}

---

## 🐞 Detailed Defect Incidents & AI Remediation

`;

  incidents.forEach((inc, index) => {
    md += `### Defect #${index + 1}: [${inc.severity}] ${inc.bug_type}

- **Faulty Selector / Node:** \`${inc.selector || "window.runtime"}\`
- **Target File:** \`${inc.target_file || "Unknown"}\`
- **Resolution Status:** \`${inc.status}\`

#### 💥 Error Trace:
\`\`\`
${inc.message}
\`\`\`

#### 🔍 Root Cause Analysis (English):
${inc.root_cause_en || "Analyzed by Ghost-QA Heuristic Engine."}

#### 🇺🇿 Texnik Tahlil (O'zbekcha):
${inc.root_cause_uz || "Ghost-QA AI mexanizmi tomonidan tahlil qilindi."}

#### ⚡ Unified Git Diff Patch:
\`\`\`diff
${inc.diff || "// No diff recorded"}
\`\`\`

---
`;
  });

  md += `
## 🏁 Verification & Compliance Sign-Off
All defects identified in this report have been cataloged with high-resolution viewport snapshots and reproducible stack traces.
*Report autonomously compiled by Ghost-QA Sentinel v2.0.*
`;

  // Trigger client download
  const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `ghost-qa-audit-report-${dateFormatted.replace(/\//g, "-")}.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
